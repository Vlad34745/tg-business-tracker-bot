def t(key: str, lang: str, **kwargs) -> str:
    """
    Look up a translated string by key for the given language, falling
    back to Ukrainian (the bot's original language) if the key or
    language is missing, and formatting in any kwargs.
    """
    entry = TRANSLATIONS.get(key)
    if not entry:
        return key  # missing key — show the key itself so it's obvious in testing
    text = entry.get(lang) or entry.get("uk") or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text